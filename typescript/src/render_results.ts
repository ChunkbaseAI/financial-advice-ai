import type { CheckerProtocol } from "./checker_protocol.ts";
import { CATEGORIES, type Category } from "./case_set_schema.ts";
import { median, type ScoredRun } from "./scorer.ts";

export interface ResultsDocumentInput {
  scoredRuns: ScoredRun[];
  timingRuns: ScoredRun[];
  protocol: CheckerProtocol;
  scorerCommit: string;
  caseSetCards: number;
}

function usd(amount: number): string {
  return `$${amount.toFixed(6)}`;
}

function minDate(dates: string[]): string {
  return dates.reduce((min, date) => (date < min ? date : min));
}

function maxDate(dates: string[]): string {
  return dates.reduce((max, date) => (date > max ? date : max));
}

function range(median: number, min: number, max: number): string {
  return max === min ? `${median}` : `${median} (${min}-${max})`;
}

function catchRateFor(run: ScoredRun, category: Category): string {
  const rates = run.repeats.map((repeat) => {
    const count = repeat.byCategory[category];
    if (count.total === 0) return null;
    return category === "correct" ? (count.passed ?? 0) / count.total : (count.caught ?? 0) / count.total;
  });
  const present = rates.filter((rate): rate is number => rate !== null);
  if (present.length === 0) return "-";
  const sorted = [...present].sort((a, b) => a - b);
  const mid = Math.floor(sorted.length / 2);
  const medianRate = sorted.length % 2 === 1 ? sorted[mid]! : (sorted[mid - 1]! + sorted[mid]!) / 2;
  return `${Math.round(medianRate * 100)}%`;
}

export function renderResultsDocument(input: ResultsDocumentInput): string {
  const { scoredRuns, timingRuns, protocol, scorerCommit, caseSetCards } = input;
  const lines: string[] = [];
  const push = (text = "") => lines.push(text);

  const repeatCounts = new Set(scoredRuns.map((run) => run.manifest.repeat_count));
  const repeatCount = repeatCounts.size === 1 ? [...repeatCounts][0]! : [...repeatCounts].join(" / ");
  const runDates = [...scoredRuns, ...timingRuns].map((run) => run.manifest.created_at.slice(0, 10));
  const runDay = new Set(runDates).size === 1 ? runDates[0]! : `${minDate(runDates)} to ${maxDate(runDates)}`;
  const totalSpend = scoredRuns.concat(timingRuns).reduce((sum, run) => sum + run.summary.totalCost, 0);
  const totalMarketSpend = scoredRuns.concat(timingRuns).reduce((sum, run) => sum + run.summary.marketCostTotal, 0);

  push("# Checker experiment results v1");
  push();
  push(
    "This document is generated from the saved run records by the pinned scorer with zero new model calls. " +
      "Do not edit it by hand; regenerate it with `bun run experiment:score`.",
  );
  push();
  const scoredProtocols = [...new Set(scoredRuns.map((run) => `${run.manifest.protocol_version} (sha256 ${run.manifest.protocol_sha256.slice(0, 16)})`))];
  const timingProtocols = [...new Set(timingRuns.map((run) => `${run.manifest.protocol_version} (sha256 ${run.manifest.protocol_sha256.slice(0, 16)})`))];
  push(`- Generated by scorer commit ${scorerCommit}`);
  push(`- Protocol for scored arms: ${scoredProtocols.join(", ") || "?"}`);
  if (timingProtocols.length > 0) push(`- Protocol for timing arms: ${timingProtocols.join(", ")}`);
  push(`- Case set ${scoredRuns[0]?.manifest.case_set_version ?? "?"} at sha256 ${scoredRuns[0]?.manifest.case_set_sha256 ?? ""}`);
  push(`- Sample: ${caseSetCards} cards, ${repeatCount} repeat(s) per scored arm`);
  push(`- All scored arms ran back to back on ${runDay}`);
  push(`- Total gateway-reported charged spend across all arms: ${usd(totalSpend)} (0 where calls are covered by credits)`);
  push(`- Total gateway-reported list-price (market) spend across all arms: ${usd(totalMarketSpend)}`);
  push();

  push("## Limitations");
  push();
  push("Written and frozen in the protocol before any model run; they bound every number below.");
  push();
  for (const limitation of protocol.limitations) {
    push(`- ${limitation}`);
  }
  push();

  push("## Headline results");
  push();
  push(
    "Dangerous passes are corrupted cards accepted (the headline risk number). Nuisance flags are correct cards sent to review " +
      "(the wasted-review number). A cautious checker must not look better merely for flagging everything, so both are shown together. " +
      "Medians across the repeats, with min-max in parentheses. Latency is gateway-reported. Consistent does not mean correct.",
  );
  push();
  push(
    "Latency is median with p95 in parentheses. The cost column is the gateway-reported list-price (market) cost per card evaluation - " +
      "the charged cost is mostly $0.000000 here because the calls were covered by credits, so it would hide every difference; both are shown in the Cost section.",
  );
  push();
  push("| Arm | Decision policy | Dangerous passes | Nuisance flags | Median latency (ms, p95) | List-price cost per card evaluation |");
  push("| --- | --- | --- | --- | --- | --- |");
  for (const run of scoredRuns) {
    const { summary } = run;
    const latency =
      summary.latencyMedianMs === null
        ? "-"
        : `${summary.latencyMedianMs} (${summary.latencyP95Ms ?? "-"})`;
    push(
      `| ${run.armName} | ${run.manifest.arm.decision_policy} | ${range(summary.dangerousPasses.median, summary.dangerousPasses.min, summary.dangerousPasses.max)} | ${range(summary.nuisanceFlags.median, summary.nuisanceFlags.min, summary.nuisanceFlags.max)} | ${latency} | ${usd(summary.marketCostPerCardEvaluation)} |`,
    );
  }
  push();

  push("## Category grid");
  push();
  push(
    "Catch rate per corruption category (share of the category's cards sent to review, median across repeats); " +
      "the `correct` column is the share passed. Per-category counts are small, so these are observed rates, not accuracy claims.",
  );
  push();
  const header = ["Arm", ...CATEGORIES.map((category) => (category === "correct" ? "correct (passed)" : category))];
  push(`| ${header.join(" | ")} |`);
  push(`| ${header.map(() => "---").join(" | ")} |`);
  for (const run of scoredRuns) {
    push(`| ${run.armName} | ${CATEGORIES.map((category) => catchRateFor(run, category)).join(" | ")} |`);
  }
  push();

  push("## Stability across repeats");
  push();
  push(
    "Action flips are cards switching between pass and review across a configuration's valid evaluations; " +
      "pass then review then pass is one flipped card. Verdict changes are review-bound verdict changes without a pass/review switch. " +
      "Denominators are cards with three valid evaluations; cards without them are listed separately and never counted as passes or catches.",
  );
  push();
  push("| Arm | Action flips | Verdict changes | Cards with three valid evaluations | Cards without |");
  push("| --- | --- | --- | --- | --- |");
  for (const run of scoredRuns) {
    const { summary } = run;
    push(
      `| ${run.armName} | ${summary.actionFlips.count}/${summary.actionFlips.denominator} | ${summary.verdictChanges.count}/${summary.verdictChanges.denominator} | ${summary.cardsWithAllRepeats} | ${summary.incompleteCards.length === 0 ? "none" : summary.incompleteCards.join(", ")} |`,
    );
  }
  push();

  push("## Errors and structured-output failures");
  push();
  push(
    "Execution errors are failures to obtain a usable checker response; input-preparation errors happen before any checker call. " +
      "Neither is ever counted as a pass or a caught mistake. Structured-output failures are shown first-attempt and remaining-after-retry.",
  );
  push();
  push("| Arm | Execution errors | Input-preparation errors | First-attempt schema failures | Remaining after retry |");
  push("| --- | --- | --- | --- | --- |");
  for (const run of scoredRuns) {
    const { summary } = run;
    push(
      `| ${run.armName} | ${summary.executionErrors} | ${summary.inputPreparationErrors} | ${summary.structuredOutputFirstAttemptFailures} | ${summary.structuredOutputRemainingAfterRetry} |`,
    );
  }
  push();

  const jevRuns = scoredRuns.filter((run) => run.calibration !== null);
  if (jevRuns.length > 0) {
    push("## Exploratory calibration (Jev)");
    push();
    push(
      "When Jev assigns a high probability to the value-support question, how often is the value truly present in the span? " +
        "Ground truth is the frozen case set's value-presence property. Three repeats of fifty cards do not establish production-safe thresholds; " +
        "this section is exploratory only. Probabilities are actual answer probabilities, never Jev's separate confidence field.",
    );
    push();
    for (const run of jevRuns) {
      push(`### ${run.armName}`);
      push();
      push("| Probability band | Samples | Observed present rate | Mean probability |");
      push("| --- | --- | --- | --- |");
      for (const band of run.calibration!.bands) {
        push(`| ${band.label} | ${band.count} | ${band.observedTrueRate === null ? "-" : `${Math.round(band.observedTrueRate * 100)}%`} | ${band.meanProbability === null ? "-" : band.meanProbability.toFixed(3)} |`);
      }
      push();
    }
  }

  push("## Cost");
  push();
  push(
    "All costs are gateway-reported for completed calls, including retries and billed failed attempts. " +
      "Charged cost is what the gateway billed (0 when calls are covered by credits, for example free tier); " +
      "the list-price column is the gateway-reported market cost, what the calls would cost at list price - never a client-side estimate. " +
      "Cost per card evaluation is total cost across all repeats divided by cards times repeats.",
  );
  push();
  push("| Arm | Charged cost per card evaluation | List-price cost per card evaluation | Average charged cost per run | Total charged |");
  push("| --- | --- | --- | --- | --- |");
  for (const run of scoredRuns) {
    push(
      `| ${run.armName} | ${usd(run.summary.costPerCardEvaluation)} | ${usd(run.summary.marketCostPerCardEvaluation)} | ${usd(run.summary.costPerRun)} | ${usd(run.summary.totalCost)} |`,
    );
  }
  push();

  push("## Failure gallery");
  push();
  push(
    "Representative failures per checker, quoting the saved records: wrong cards passed (dangerous passes) first, " +
      "then correct cards sent to review (nuisance flags). The quoted text is the checker's stated answer, not evidence of its internal reasoning.",
  );
  push();
  for (const run of scoredRuns) {
    push(`### ${run.armName}`);
    push();
    const dangerous = run.failures.filter((f) => f.kind === "dangerous-pass");
    const nuisance = run.failures.filter((f) => f.kind === "nuisance-flag");
    const execution = run.failures.filter((f) => f.kind === "execution-error");
    const quoted = dangerous.length + nuisance.length + execution.length;
    if (quoted === 0) {
      push("No dangerous passes, nuisance flags or execution errors in this arm's records.");
      push();
      continue;
    }
    if (quoted < 3) {
      push(
        `This arm's records contain only ${quoted} failure(s) in total, so fewer than three are quoted here; every one that exists is shown.`,
      );
      push();
    }
    if (dangerous.length > 0) {
      push("Wrong cards passed:");
      push();
      for (const failure of dangerous.slice(0, 3)) {
        push(`- **${failure.cardId}** (${failure.category}, expected ${failure.expected}), repeat ${failure.repeat}: claim — ${failure.claim}. Checker said: "${failure.quote}"`);
      }
      push();
    }
    if (nuisance.length > 0) {
      push("Correct cards sent to review:");
      push();
      for (const failure of nuisance.slice(0, 3)) {
        push(`- **${failure.cardId}** (${failure.category}, expected ${failure.expected}), repeat ${failure.repeat}: claim — ${failure.claim}. Checker said: "${failure.quote}"`);
      }
      push();
    }
    if (execution.length > 0) {
      push("Execution errors:");
      push();
      for (const failure of execution.slice(0, 3)) {
        push(`- **${failure.cardId}** (${failure.category}), repeat ${failure.repeat}: claim — ${failure.claim}. ${failure.quote}`);
      }
      push();
    }
  }

  if (timingRuns.length > 0) {
    push("## Verdict-only timing runs (not scored)");
    push();
    push(
      "These runs asked for the verdict with no reason field, to compare speed against Jev's no-reason answers on a like-for-like basis. " +
        "They are separately labelled, use one repeat, and no correctness number in this document comes from them.",
    );
    push();
    push("| Arm | Repeat count | Median latency (ms) | p95 latency (ms) | Cost per card evaluation |");
    push("| --- | --- | --- | --- | --- |");
    for (const run of timingRuns) {
      push(
        `| ${run.armName} | ${run.manifest.repeat_count} | ${run.summary.latencyMedianMs ?? "-"} | ${run.summary.latencyP95Ms ?? "-"} | ${usd(run.summary.costPerCardEvaluation)} |`,
      );
    }
    push();
  }

  push("## What the comparison shows");
  push();
  push(
    "Reading the headline table with the category grid together, under the frozen protocol and its limitations. " +
      "Every number in this section is derived from the same scored records as the tables above.",
  );
  push();

  const rulesRun = scoredRuns.find((run) => run.manifest.arm.variant === "rules");
  const jevRun = scoredRuns.find((run) => run.manifest.arm.variant === "decomposed");
  const llmArms = scoredRuns.filter((run) => run.manifest.arm.decision_policy === "categorical-verdict");
  if (rulesRun !== undefined && rulesRun.repeats.length > 0) {
    const grid = rulesRun.repeats[0]!.byCategory;
    const corruptedTotal = CATEGORIES.filter((c) => c !== "correct").reduce((sum, c) => sum + (grid[c]?.total ?? 0), 0);
    push(
      `- The rules checker passes ${rulesRun.summary.dangerousPasses.median} of ${corruptedTotal} corrupted cards per repeat (median): ` +
        `every wrong-subject, stale-value, hypothetical and wrong-basis card, exactly the dangerous passes the case set was built to demonstrate. ` +
        "Value-presence matching is not checking.",
    );
    push();
  }
  if (jevRun !== undefined) {
    const grid = jevRun.repeats[0]!.byCategory;
    const sneaky: Category[] = ["wrong-subject", "stale-value", "hypothetical", "wrong-basis"];
    const sneakyAllCaught = jevRun.repeats.every((repeat) =>
      sneaky.every((c) => (repeat.byCategory[c]?.caught ?? 0) === (repeat.byCategory[c]?.total ?? 0)),
    );
    const correctPassRates = jevRun.repeats.map((repeat) => {
      const correct = repeat.byCategory["correct"]!;
      return correct.total === 0 ? 0 : (correct.passed ?? 0) / correct.total;
    });
    const correctPassMedian = Math.round(median(correctPassRates) * 100);
    const networkedCosts = scoredRuns
      .filter((run) => run.manifest.arm.variant !== "rules")
      .map((run) => run.summary.marketCostPerCardEvaluation);
    const cheapestNetworked = networkedCosts.length > 0 && jevRun.summary.marketCostPerCardEvaluation <= Math.min(...networkedCosts);
    const latencies = scoredRuns.map((run) => run.summary.latencyMedianMs).filter((l): l is number => l !== null);
    const fastest = latencies.length > 0 && jevRun.summary.latencyMedianMs === Math.min(...latencies);
    push(
      `- Jev, gated at the frozen 0.90/0.10 lines, recorded ${jevRun.summary.dangerousPasses.median} dangerous passes (median) ` +
        (sneakyAllCaught
          ? "and caught the sneaky categories the rules checker passes: wrong-subject, stale-value, hypothetical and wrong-basis all at 100% in every repeat."
          : "though it missed some cards in the sneaky categories; see the category grid.") +
        (cheapestNetworked ? " Its list-price cost was the lowest of any networked arm." : "") +
        (fastest ? " Its latency was the lowest of any arm." : ""),
    );
    const topBand = jevRun.calibration?.bands.find((band) => band.label === "0.90 - 1.00");
    const topBandHonest =
      topBand !== undefined && topBand.count > 0 && topBand.observedTrueRate !== null && topBand.observedTrueRate >= 1;
    push(
      `- Jev's price was nuisance flags: at the 0.90 threshold about ${correctPassMedian}% of correct cards passed these three checks per repeat, ` +
        "mostly because its value-support and time-support probabilities sit between the thresholds. " +
        (topBandHonest
          ? "In these runs the top calibration band is not overconfident (every 0.90+ value-support probability came with the value truly present), so the nuisance flags point at the threshold, not at wrong high-confidence answers; "
          : "The calibration section shows how often its high probabilities were right in these runs; ") +
        "where that line should sit is a question for a larger labelled set, not these three repeats.",
    );
    push();
  }
  {
    const caughtAll = llmArms.filter((run) => run.summary.dangerousPasses.max === 0);
    const passedSome = llmArms.filter((run) => run.summary.dangerousPasses.max > 0);
    const passedSomeList = passedSome.map((run) => `${run.armName} (${run.summary.dangerousPasses.median} median, max ${run.summary.dangerousPasses.max})`);
    const caughtAllList = caughtAll.map((run) => run.armName);
    const list = (names: string[]) => (names.length <= 1 ? names.join("") : `${names.slice(0, -1).join(", ")} and ${names[names.length - 1]!}`);
    push(
      `- The generative checkers sit between: ${caughtAllList.length > 0 ? `${list(caughtAllList)} passed no corrupted cards in any repeat` : "no generative arm passed zero corrupted cards in every repeat"}, ` +
        `while ${passedSomeList.length > 0 ? passedSomeList.join(", ") : "none"} passed corrupted cards. ` +
        "Every arm that caught all corrupted cards did so by flagging some correct ones too; no arm passed every correct card while catching everything, " +
        "and a cautious checker must not look better merely for flagging everything.",
    );
    push();
    const ratios = llmArms
      .filter((run) => run.armName.endsWith("-three"))
      .map((three) => {
        const overall = llmArms.find((run) => run.armName === three.armName.replace(/-three$/, "-overall"));
        if (overall === undefined || overall.summary.marketCostPerCardEvaluation === 0) return null;
        return three.summary.marketCostPerCardEvaluation / overall.summary.marketCostPerCardEvaluation;
      })
      .filter((ratio): ratio is number => ratio !== null);
    if (ratios.length > 0) {
      push(
        `- The three-question configurations cost roughly ${Math.min(...ratios).toFixed(1)}-${Math.max(...ratios).toFixed(1)}x their overall counterparts per card at list price; ` +
          "compare their catch and nuisance numbers in the tables above rather than taking decomposition as free.",
      );
      push();
    }
    const execFailureArm = scoredRuns.reduce<ScoredRun | undefined>(
      (worst, run) => (run.summary.executionErrors > 0 && (worst === undefined || run.summary.executionErrors > worst.summary.executionErrors) ? run : worst),
      undefined,
    );
    if (execFailureArm !== undefined) {
      push(
        `- ${execFailureArm.armName} is the largest structured-output failure case: ${execFailureArm.summary.executionErrors} of ` +
          `${execFailureArm.records.length} evaluations died as execution errors (both attempts invalid; see the errors table for first-attempt counts). ` +
          "Those are never counted as passes or catches, and the gallery quotes them.",
      );
      push();
    }
  }

  push("## Protocol history");
  push();
  push(
    "Three frozen protocol versions produced this document, each bump forced by a failure that changed the design, with every superseded run preserved:",
  );
  push();
  push(
    "- 0.1.0 -> 0.2.0: the 300-token reasoned output limit truncated three-question responses (111/150 execution errors on the claude-sonnet-5-three pre-batch run); 0.2.0 raised it to 1000 and the batch was rerun.",
  );
  push(
    "- 0.2.0 -> 0.3.0: the 100-token verdict-only limit truncated gemini-3.8-flash timing responses with empty content (hidden reasoning tokens precede visible output); 0.3.0 raised it to 1000 and the timing arms were rerun. The change touches a parameter scored arms never use, and 0.3.0 declares 0.2.0 scored runs compatible by hash; the scorer verifies that declaration.",
  );
  push(
    "- The pre-batch free-tier blocker (all four pinned LLMs returned 403 RestrictedModelsError until credits were added) is documented in the experiment write-up, not the records: no model was substituted.",
  );
  push();
  push("## What these runs do not show");
  push();
  push(
    "This experiment tests checking of supplied Claims against supplied Evidence Spans only. It does not test extraction or generation, " +
      "it uses one frozen synthetic case set from one author, and it makes no suitability, compliance, cross-vendor leaderboard, or \"first\" claim. " +
      "The pass outcome is named \"passed these three checks\" where three checks ran, and it never means fully verified; " +
      "\"unsupported\" means the source lacks or contradicts the claimed support, never that the card is proven wrong.",
  );
  push();

  return `${lines.join("\n")}\n`;
}
